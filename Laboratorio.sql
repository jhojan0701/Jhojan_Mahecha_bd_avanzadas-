-- Todos los empleados del XML

SELECT x.id,
       x.nombre,
       x.apellido,
       x.correo,
       x.salario,
       x.departamento
FROM empleados_xml t,
     XMLTABLE(
       '/empleados/empleado'
       PASSING t.documento
       COLUMNS
         id VARCHAR2(20) PATH '@id',
         nombre VARCHAR2(100) PATH 'nombre',
         apellido VARCHAR2(100) PATH 'apellido',
         correo VARCHAR2(150) PATH 'correo',
         salario VARCHAR2(50) PATH 'salario',
         departamento VARCHAR2(100) PATH 'departamento'
     ) x
WHERE t.observacion = 'XML válido'
ORDER BY TO_NUMBER(x.id);

