SELECT e.id_empleado,
       e.nombre,
       e.apellido,
       e.correo,
       e.salario,
       d.nombre_departamento AS departamento
FROM empleados e
JOIN departamentos d
ON e.id_departamento = d.id_departamento
ORDER BY e.id_empleado;

